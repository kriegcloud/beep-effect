#!/usr/bin/env node

import { CodegenPostProcessError, GenerateConfig, runGenerateCli } from "@beep/codegen-kit";
import { $AcpId } from "@beep/identity";
import * as A from "effect/Array";
import * as Effect from "effect/Effect";
import { pipe } from "effect/Function";
import * as S from "effect/Schema";
import type { ExtraRenderer, NamedTransform, SpecSource } from "@beep/codegen-kit";

/** Pinned ACP generation-2 schema release (GitHub prerelease tag). */
const V2_SCHEMA_RELEASE = "schema-v2.0.0-alpha.3";
/** Pinned ACP generation-1 schema release (GitHub release tag). */
const V1_SCHEMA_RELEASE = "schema-v1.21.0";

const packageRoot = `${import.meta.dirname}/..`;
const $I = $AcpId.create("scripts/generate");

const releaseAsset = (tag: string, asset: string): string =>
  `https://github.com/agentclientprotocol/agent-client-protocol/releases/download/${tag}/${asset}`;

/**
 * Generation 2 keeps the historical cache paths (`spec/*.unstable.json`) so consumers that read the
 * cache by path keep working; generation 1 caches live under `spec/v1/`.
 */
const cachedAsset = (tag: string, cacheDir: string, asset: string): SpecSource => ({
  _tag: "url",
  url: releaseAsset(tag, asset),
  pin: tag,
  pinPolicy: "url-embedded",
  cachePath: `${packageRoot}/${cacheDir}/${asset}`,
});

const V2_CACHE_DIR = "spec";
const V1_CACHE_DIR = "spec/v1";

/**
 * JSON Schema normalizations the pinned specs need before the Effect importer can read them:
 * nullable type arrays, `unevaluatedProperties: true`, forward-compatible `not` discriminator
 * exclusions, discriminated `oneOf` as `anyOf`, and `allOf` distribution over unions.
 */
const acpTransforms: ReadonlyArray<NamedTransform> = [
  "nullableTypeArray",
  "unevaluatedPropertiesOpen",
  "notDiscriminatorPattern",
  "uniqueDiscriminatorOneOfAsAnyOf",
  "distributeAllOf",
];

class MetaJson extends S.Opaque<MetaJson, { readonly brand: unique symbol }>()(
  S.Struct({
    agentMethods: S.Record(S.String, S.String),
    clientMethods: S.Record(S.String, S.String),
    version: S.Union([S.Finite, S.String]),
  }).pipe(
    $I.annoteSchema("MetaJson", {
      description: "ACP upstream metadata JSON consumed by the package-specific extra renderer.",
    })
  )
) {}

const generatedHeader = (release: string): string =>
  pipe(
    [
      "/**",
      " * Generated ACP protocol schema and metadata modules.",
      " *",
      " * @packageDocumentation",
      " * @since 0.0.0",
      " */",
      "",
      "// This file is generated by the @beep/acp package. Do not edit manually.",
      `// Current ACP schema release: ${release}`,
    ],
    A.join("\n")
  );

const renderMetaConst = (name: string, value: string, description: string): string =>
  pipe(
    [
      "/**",
      ` * ${description}`,
      " *",
      ` * **Example** (Read ${name})`,
      " *",
      " * ```ts",
      ` * import { ${name} } from "@beep/acp/schema"`,
      " *",
      ` * console.log(${name})`,
      " * ```",
      " *",
      " * @category constants",
      " * @since 0.0.0",
      " */",
      `export const ${name} = ${value} as const;`,
    ],
    A.join("\n")
  );

const decodeMeta = S.decodeUnknownEffect(MetaJson);
const encodeMethods = S.encodeUnknownEffect(S.fromJsonString(MetaJson.fields.agentMethods));
const encodeVersion = S.encodeUnknownEffect(S.fromJsonString(MetaJson.fields.version));

const postProcessError = (message: string) => (cause: unknown) => CodegenPostProcessError.make({ message, cause });

type MetaFetch = Parameters<ExtraRenderer>[2];

const renderMetaRelease = Effect.fn("Acp.generateMeta.release")(function* (
  fetch: MetaFetch,
  refresh: boolean,
  options: { readonly release: string; readonly cacheDir: string; readonly prefix: string; readonly label: string }
) {
  const document = yield* fetch(cachedAsset(options.release, options.cacheDir, "meta.unstable.json"), refresh);
  const meta = yield* decodeMeta(document).pipe(
    Effect.mapError(postProcessError(`Could not decode ACP ${options.label} metadata cache`))
  );
  const agentMethods = yield* encodeMethods(meta.agentMethods).pipe(
    Effect.mapError(postProcessError(`Could not render ${options.prefix}AGENT_METHODS`))
  );
  const clientMethods = yield* encodeMethods(meta.clientMethods).pipe(
    Effect.mapError(postProcessError(`Could not render ${options.prefix}CLIENT_METHODS`))
  );
  const version = yield* encodeVersion(meta.version).pipe(
    Effect.mapError(postProcessError(`Could not render ${options.prefix}PROTOCOL_VERSION`))
  );
  return [
    renderMetaConst(
      `${options.prefix}AGENT_METHODS`,
      agentMethods,
      `Generated ACP ${options.label} agent method lookup table (${options.release}).`
    ),
    "",
    renderMetaConst(
      `${options.prefix}CLIENT_METHODS`,
      clientMethods,
      `Generated ACP ${options.label} client method lookup table (${options.release}).`
    ),
    "",
    renderMetaConst(
      `${options.prefix}PROTOCOL_VERSION`,
      version,
      `Generated ACP ${options.label} protocol version (${options.release}).`
    ),
  ];
});

const renderMeta: ExtraRenderer = Effect.fn("Acp.generateMeta")(function* (_config, refresh, fetch) {
  const v2 = yield* renderMetaRelease(fetch, refresh, {
    release: V2_SCHEMA_RELEASE,
    cacheDir: V2_CACHE_DIR,
    prefix: "",
    label: "generation-2",
  });
  const v1 = yield* renderMetaRelease(fetch, refresh, {
    release: V1_SCHEMA_RELEASE,
    cacheDir: V1_CACHE_DIR,
    prefix: "V1_",
    label: "generation-1",
  });
  return pipe(
    [
      generatedHeader(`${V2_SCHEMA_RELEASE} (generation 2), ${V1_SCHEMA_RELEASE} (generation 1)`),
      "",
      'import { $AcpId } from "@beep/identity";',
      "",
      'const $I = $AcpId.create("_generated/meta.gen");',
      "void $I;",
      "",
      ...v2,
      "",
      ...v1,
      "",
    ],
    A.join("\n")
  );
});

const v2 = GenerateConfig.make({
  packageName: "@beep/acp",
  identity: { composer: "$AcpId", moduleId: "_generated/schema.gen" },
  source: cachedAsset(V2_SCHEMA_RELEASE, V2_CACHE_DIR, "schema.unstable.json"),
  dialect: "json-schema-2020-12",
  transforms: acpTransforms,
  format: "schemas",
  output: {
    path: `${packageRoot}/src/_generated/schema.gen.ts`,
    header: generatedHeader(V2_SCHEMA_RELEASE),
  },
  extraModules: [{ renderer: "acp-meta", path: `${packageRoot}/src/_generated/meta.gen.ts` }],
});

const v1 = GenerateConfig.make({
  packageName: "@beep/acp",
  identity: { composer: "$AcpId", moduleId: "_generated/schema-v1.gen" },
  source: cachedAsset(V1_SCHEMA_RELEASE, V1_CACHE_DIR, "schema.unstable.json"),
  dialect: "json-schema-2020-12",
  transforms: acpTransforms,
  format: "schemas",
  output: {
    path: `${packageRoot}/src/_generated/schema-v1.gen.ts`,
    header: generatedHeader(V1_SCHEMA_RELEASE),
    exampleImport: "@beep/acp/schema-v1",
  },
});

runGenerateCli([v2, v1], { extraRenderers: { "acp-meta": renderMeta } });
